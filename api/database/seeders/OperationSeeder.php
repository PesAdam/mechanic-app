    public function run(): void
    {
        $stored = Setting::get(self::SEEDED_KEY);
        // First run of this seeder on an install that already has a catalogue: it came from the old list.
        $offered = $stored !== null ? (json_decode((string) $stored, true) ?: []) : (Operation::query()->exists() ? self::LEGACY_NAMES : []);
        $existing = Operation::query()->pluck('id', 'name');

        foreach (self::CATALOG as $category => $jobs) {
            foreach ($jobs as $name => $minutes) {
                if (! isset($existing[$name]) && ! in_array($name, $offered, true)) {
                    Operation::query()->create(['name' => $name, 'category' => $category, 'norm_minutes' => $minutes]);
                }
            }
        }

        Setting::set(self::SEEDED_KEY, json_encode(array_values(array_unique(array_merge($offered, self::names()))), JSON_UNESCAPED_UNICODE));
    }

    /** @return list<string> */
    public static function names(): array
    {
        return array_merge(...array_map(fn (array $jobs) => array_keys($jobs), array_values(self::CATALOG)));
    }
