    public static function factor(string $make, string $model, ?string $engine, string $category): float
    {
        $area = self::AREAS[$category] ?? null;
        $entry = self::MODELS[$make][$model] ?? null;
        if ($area === null || $entry === null) {
            return 1.0;
        }

        $factor = $entry[0][$area];
        if ($area === self::ENGINE_AREA && $engine !== null) {
            $factor *= $entry[1][$engine] ?? 1.0;
        }

        return $factor;
    }

    /** Engine-area jobs differ between engines of one model, so their times are kept per engine. */
    public static function followsEngine(string $category): bool
    {
        return (self::AREAS[$category] ?? null) === self::ENGINE_AREA;
    }
