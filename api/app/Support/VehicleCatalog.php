    public static function logoUrl(?string $slug): ?string
    {
        return $slug ? self::LOGO_BASE.$slug.'.png' : null;
    }

    /** Slug for a make typed by name, if the catalogue knows it. */
    public static function slugFor(string $name): ?string
    {
        foreach (self::makes() as $make => $def) {
            if (mb_strtolower($make) === mb_strtolower(trim($name))) {
                return $def['slug'];
            }
        }

        return null;
    }
